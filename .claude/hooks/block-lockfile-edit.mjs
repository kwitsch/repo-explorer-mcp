#!/usr/bin/env node
// PreToolUse (Edit|Write) guard: Cargo.lock/package-lock.json are generated
// files — hand-edits drift from what `cargo build`/`npm install` would write.
let data = "";
process.stdin.on("data", (c) => (data += c));
process.stdin.on("end", () => {
  let input;
  try {
    input = JSON.parse(data);
  } catch {
    process.exit(0);
  }
  const filePath = input.tool_input && input.tool_input.file_path;
  if (!filePath) process.exit(0);
  const base = filePath.replace(/\\/g, "/").split("/").pop();
  const manifest = {
    "Cargo.lock": ["cargo build", "Cargo.toml"],
    "package-lock.json": ["npm install", "package.json"],
  }[base];
  if (manifest) {
    const [regen, source] = manifest;
    process.stderr.write(
      `${base} is generated by \`${regen}\` — edit ${source} and regenerate instead of hand-editing the lock file.\n`,
    );
    process.exit(2);
  }
  process.exit(0);
});
